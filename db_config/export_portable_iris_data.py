def _format_csv_value(
    value: Any,
    column_info: ColumnInfo | None,
    null_value: str = NULL_SENTINEL,
) -> str:
    """Format a database value for CSV export."""
    if value is None:
        return null_value
    if column_info and _is_json_column(column_info):
        return _json_text(value)
    if column_info and _is_array_column(column_info):
        return _pg_array_literal(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, bytes):
        return _bytes_to_text(value)
    return str(value)


def _format_sql_value(value: Any, column_info: ColumnInfo | None) -> str:
    """Format a database value as a PostgreSQL literal."""
    if value is None:
        return "NULL"
    if column_info and _is_json_column(column_info):
        return f"{_quote_sql_string(_json_text(value))}::{column_info.udt_name}"
    if column_info and _is_array_column(column_info):
        return f"{_quote_sql_string(_pg_array_literal(value))}::{_array_sql_type(column_info)}"
    if column_info and _is_vector_column(column_info):
        return f"{_quote_sql_string(str(value))}::{column_info.udt_name}"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float, Decimal)) and not isinstance(value, bool):
        return str(value)
    if isinstance(value, (datetime, date, time)):
        return _quote_sql_string(value.isoformat())
    if isinstance(value, bytes):
        return _quote_sql_string(_bytes_to_text(value))
    return _quote_sql_string(str(value))


def _json_text(value: Any) -> str:
    """Render a JSON-compatible value as compact JSON text."""
    if isinstance(value, str):
        return value
    return json.dumps(
        value,
        default=_json_default,
        ensure_ascii=False,
        separators=(",", ":"),
    )


def _json_default(value: Any) -> str:
    """Convert non-standard JSON values used by psycopg2."""
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, bytes):
        return _bytes_to_text(value)
    raise TypeError(f"Object is not JSON serializable: {type(value)!r}")


def _pg_array_literal(value: Any) -> str:
    """Render a Python or PostgreSQL array value as a PostgreSQL array literal."""
    if isinstance(value, str):
        return value
    if value is None:
        return "{}"
    rendered = []
    for item in value:
        if item is None:
            rendered.append("NULL")
            continue
        text = str(item)
        escaped = text.replace("\\", "\\\\").replace('"', '\\"')
        needs_quotes = (
            escaped == ""
            or escaped.upper() == "NULL"
            or any(char in escaped for char in [",", "{", "}", '"', "\\"])
            or any(char.isspace() for char in escaped)
        )
        rendered.append(f'"{escaped}"' if needs_quotes else escaped)
    return "{" + ",".join(rendered) + "}"


def _quote_sql_string(value: str) -> str:
    """Quote and escape a PostgreSQL string literal."""
    return "'" + value.replace("'", "''") + "'"


def _bytes_to_text(value: bytes) -> str:
    """Decode bytes as UTF-8 or hex when text decoding fails."""
    try:
        return value.decode("utf-8")
    except UnicodeDecodeError:
        return value.hex()


def _array_sql_type(column_info: ColumnInfo) -> str:
    """Return a PostgreSQL type cast for an array column."""
    if column_info.udt_name in ARRAY_TYPE_CASTS:
        return ARRAY_TYPE_CASTS[column_info.udt_name]
    if column_info.udt_name.startswith("_"):
        return f"{column_info.udt_name[1:]}[]"
    return "text[]"


def _is_json_column(column_info: ColumnInfo) -> bool:
    """Return whether a column uses PostgreSQL JSON storage."""
    return column_info.udt_name in {"json", "jsonb"} or column_info.data_type in {
        "json",
        "jsonb",
    }


def _is_array_column(column_info: ColumnInfo) -> bool:
    """Return whether a column uses a PostgreSQL array type."""
    return column_info.data_type == "ARRAY" or column_info.udt_name.startswith("_")


def _is_vector_column(column_info: ColumnInfo) -> bool:
    """Return whether a column uses a pgvector-compatible vector type."""
    return column_info.udt_name in {"vector", "halfvec", "sparsevec"}


def _column_names(columns: Sequence[ColumnInfo]) -> list[str]:
    """Return column names from column metadata."""
    return [column.name for column in columns]


def _column_map(columns: Sequence[ColumnInfo]) -> dict[str, ColumnInfo]:
    """Return column metadata keyed by column name."""
    return {column.name: column for column in columns}


def _chunk_csv_columns(columns: Sequence[ColumnInfo]) -> list[str]:
    """Return CSV columns for chunks, including document natural keys."""
    return ["document_db_source", "document_name", *_column_names(columns)]


def _column_sql_list(columns: Sequence[str]) -> str:
    """Return a comma-separated SQL identifier list."""
    return ", ".join(_ident(column) for column in columns)


def _ident(identifier: str) -> str:
    """Quote a PostgreSQL identifier."""
    return '"' + identifier.replace('"', '""') + '"'


