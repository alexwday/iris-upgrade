#!/usr/bin/env python3
"""
Portable IRIS Data Export - Environment-to-environment transfer files.

This module exports the IRIS registry, document metadata, document chunks, and
latest IRIS prompts from PostgreSQL into portable CSV and SQL artifacts. It is
intended for moving IRIS configuration and document retrieval data between
environments without copying generated identifiers or timestamps from the source
database.

Generated fields are intentionally omitted. During import, prompt IDs, document
UUIDs, chunk UUIDs, and timestamp columns are regenerated by PostgreSQL defaults.
Chunk rows are relinked to their regenerated document UUIDs by using the stable
document key pair of db_source and document_name.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from dataclasses import dataclass
from datetime import date, datetime, time
from decimal import Decimal
from pathlib import Path
from typing import Any, Iterable, Iterator, Sequence

import psycopg2
from psycopg2 import sql

try:
    from dotenv import load_dotenv

    load_dotenv()
    load_dotenv(".env.local", override=True)
except ImportError:
    pass


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT_ROOT = SCRIPT_DIR / "exports"
NULL_SENTINEL = r"\N"

REGISTRY_TABLE = "iris_database_registry"
METADATA_TABLE = "iris_document_metadata"
CHUNKS_TABLE = "iris_document_chunks"
PROMPTS_TABLE = "prompts"

REGISTRY_FILE = "iris_database_registry.csv"
METADATA_FILE = "iris_document_metadata.csv"
CHUNKS_FILE = "iris_document_chunks.csv"
PROMPTS_FILE = "iris_prompts_latest.csv"
INLINE_SQL_FILE = "iris_portable_import.sql"
CSV_IMPORT_SQL_FILE = "import_from_csv.sql"
README_FILE = "README.md"
MANIFEST_FILE = "manifest.json"
DIRECT_TABLE_CSV_DIR = "direct_table_csv"
DIRECT_UPLOAD_SQL_FILE = "after_direct_upload.sql"
IT_UPLOAD_CSV_DIR = "it_upload_csv"

GENERATED_COLUMNS = {
    REGISTRY_TABLE: {"created_at", "updated_at"},
    PROMPTS_TABLE: {"id", "created_at", "updated_at"},
    METADATA_TABLE: {"id", "created_at", "updated_at"},
    CHUNKS_TABLE: {"id", "document_id", "created_at", "updated_at"},
}

ARRAY_TYPE_CASTS = {
    "_text": "text[]",
    "_varchar": "character varying[]",
    "_bpchar": "character[]",
    "_int2": "smallint[]",
    "_int4": "integer[]",
    "_int8": "bigint[]",
    "_float4": "real[]",
    "_float8": "double precision[]",
    "_bool": "boolean[]",
    "_uuid": "uuid[]",
}


@dataclass(frozen=True)
class ColumnInfo:
    """PostgreSQL column metadata used to format portable export values."""

    name: str
    data_type: str
    udt_name: str
    character_maximum_length: int | None
    numeric_precision: int | None
    numeric_scale: int | None
    is_nullable: str
    column_default: str | None
    ordinal_position: int


def main() -> None:
    """Export portable IRIS data files.

    Returns:
        None.
    """
    args = _parse_args()
    settings = _connection_settings()
    output_dir = _resolve_output_dir(args.output_dir)

    print("Portable IRIS data export")
    print(f"  Host:     {settings['host']}")
    print(f"  Port:     {settings['port']}")
    print(f"  Database: {settings['database']}")
    print(f"  User:     {settings['user']}")

    try:
        conn = _get_connection(settings)
    except psycopg2.Error as exc:
        print(f"\nERROR: Could not connect to PostgreSQL: {exc}")
        sys.exit(1)

    try:
        table_columns = _load_export_columns(conn)
        export_plan = _build_export_plan(table_columns)

        if args.dry_run:
            _print_dry_run(conn, table_columns, export_plan)
            return

        output_dir.mkdir(parents=True, exist_ok=True)

        registry_rows = list(_iter_registry_rows(conn, export_plan[REGISTRY_TABLE]))
        prompt_rows = list(
            _iter_latest_iris_prompt_rows(conn, export_plan[PROMPTS_TABLE])
        )
        metadata_rows = list(_iter_metadata_rows(conn, export_plan[METADATA_TABLE]))

        print(f"\nWriting CSV exports to: {output_dir}")
        registry_count = _write_csv(
            output_dir / REGISTRY_FILE,
            _column_names(export_plan[REGISTRY_TABLE]),
            registry_rows,
            _column_map(export_plan[REGISTRY_TABLE]),
        )
        prompt_count = _write_csv(
            output_dir / PROMPTS_FILE,
            _column_names(export_plan[PROMPTS_TABLE]),
            prompt_rows,
            _column_map(export_plan[PROMPTS_TABLE]),
        )
        metadata_count = _write_csv(
            output_dir / METADATA_FILE,
            _column_names(export_plan[METADATA_TABLE]),
            metadata_rows,
            _column_map(export_plan[METADATA_TABLE]),
        )
        chunk_count = _write_csv(
            output_dir / CHUNKS_FILE,
            _chunk_csv_columns(export_plan[CHUNKS_TABLE]),
            _iter_chunk_rows(conn, export_plan[CHUNKS_TABLE]),
            _column_map(export_plan[CHUNKS_TABLE]),
        )

        direct_counts = _write_direct_table_csvs(output_dir, conn, table_columns)
        it_counts = _write_it_upload_csvs(
            output_dir,
            conn,
            table_columns,
            prompt_rows,
            export_plan[PROMPTS_TABLE],
        )

        print("\nWriting SQL import files")
        inline_chunk_count = _write_inline_sql(
            output_dir / INLINE_SQL_FILE,
            registry_rows,
            prompt_rows,
            metadata_rows,
            conn,
            export_plan,
        )
        _write_csv_import_sql(output_dir / CSV_IMPORT_SQL_FILE, export_plan)

        counts = {
            REGISTRY_TABLE: registry_count,
            PROMPTS_TABLE: prompt_count,
            METADATA_TABLE: metadata_count,
            CHUNKS_TABLE: chunk_count,
        }
        if inline_chunk_count != chunk_count:
            raise RuntimeError(
                "Chunk count mismatch between CSV and SQL export: "
                f"{chunk_count} CSV rows vs {inline_chunk_count} SQL rows"
            )

        _write_manifest(
            output_dir / MANIFEST_FILE,
            settings,
            table_columns,
            export_plan,
            counts,
            direct_counts,
            it_counts,
        )
        _write_readme(output_dir / README_FILE, counts, direct_counts, it_counts)

        print("\nExport complete")
        print(f"  Output: {output_dir}")
        print(f"  Registry rows: {registry_count}")
        print(f"  Latest IRIS prompts: {prompt_count}")
        print(f"  Document metadata rows: {metadata_count}")
        print(f"  Document chunk rows: {chunk_count}")
        print(f"  IT upload CSV directory: {output_dir / IT_UPLOAD_CSV_DIR}")
        print(f"  Direct CSV directory: {output_dir / DIRECT_TABLE_CSV_DIR}")
    finally:
        conn.close()


def _parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description=(
            "Export portable IRIS registry, document data, and latest prompts "
            "to CSV and SQL files."
        )
    )
    parser.add_argument(
        "--output-dir",
        help=(
            "Directory for export files. Defaults to "
            "db_config/exports/iris_portable_<timestamp>."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Connect and show export counts without writing files.",
    )
    return parser.parse_args()


def _connection_settings() -> dict[str, str]:
    """Return PostgreSQL connection settings from environment variables."""
    return {
        "host": os.getenv("VECTOR_POSTGRES_DB_HOST", "localhost"),
        "port": os.getenv("VECTOR_POSTGRES_DB_PORT", "34532"),
        "database": os.getenv("VECTOR_POSTGRES_DB_NAME", "maven-finance"),
        "user": os.getenv("VECTOR_POSTGRES_DB_USERNAME", os.getenv("USER", "postgres")),
        "password": os.getenv("VECTOR_POSTGRES_DB_PASSWORD", ""),
        "gssencmode": os.getenv("PGGSSENCMODE", ""),
        "sslmode": os.getenv("PGSSLMODE", ""),
    }


def _resolve_output_dir(output_dir: str | None) -> Path:
    """Resolve the output directory for generated export files."""
    if output_dir:
        return Path(output_dir).expanduser().resolve()
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return DEFAULT_OUTPUT_ROOT / f"iris_portable_{timestamp}"


def _get_connection(settings: dict[str, str]):
    """Create a PostgreSQL connection from normalized settings."""
    kwargs: dict[str, Any] = {
        "host": settings["host"],
        "port": settings["port"],
        "database": settings["database"],
        "user": settings["user"],
        "password": settings["password"],
    }
    if settings["gssencmode"]:
        kwargs["gssencmode"] = settings["gssencmode"]
    if settings["sslmode"]:
        kwargs["sslmode"] = settings["sslmode"]
    return psycopg2.connect(**kwargs)


def _load_export_columns(conn) -> dict[str, list[ColumnInfo]]:
    """Load exportable column metadata for all required tables."""
    return {
        REGISTRY_TABLE: _fetch_table_columns(conn, REGISTRY_TABLE),
        PROMPTS_TABLE: _fetch_table_columns(conn, PROMPTS_TABLE),
        METADATA_TABLE: _fetch_table_columns(conn, METADATA_TABLE),
        CHUNKS_TABLE: _fetch_table_columns(conn, CHUNKS_TABLE),
    }


def _fetch_table_columns(conn, table_name: str) -> list[ColumnInfo]:
    """Fetch ordered PostgreSQL column metadata for a table."""
    query = """
        SELECT
            column_name,
            data_type,
            udt_name,
            character_maximum_length,
            numeric_precision,
            numeric_scale,
            is_nullable,
            column_default,
            ordinal_position
        FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = %s
        ORDER BY ordinal_position
    """
    with conn.cursor() as cur:
        cur.execute(query, (table_name,))
        rows = cur.fetchall()

    if not rows:
        raise RuntimeError(f"Table not found or has no columns: {table_name}")

    return [
        ColumnInfo(
            name=row[0],
            data_type=row[1],
            udt_name=row[2],
            character_maximum_length=row[3],
            numeric_precision=row[4],
            numeric_scale=row[5],
            is_nullable=row[6],
            column_default=row[7],
            ordinal_position=row[8],
        )
        for row in rows
    ]


def _build_export_plan(
    table_columns: dict[str, list[ColumnInfo]],
) -> dict[str, list[ColumnInfo]]:
    """Remove generated columns and validate required import keys."""
    plan: dict[str, list[ColumnInfo]] = {}
    for table_name, columns in table_columns.items():
        excluded = GENERATED_COLUMNS[table_name]
        plan[table_name] = [column for column in columns if column.name not in excluded]

    _require_columns(plan[REGISTRY_TABLE], ["db_source"], REGISTRY_TABLE)
    _require_columns(
        plan[PROMPTS_TABLE],
        ["model", "layer", "name", "version"],
        PROMPTS_TABLE,
    )
    _require_columns(
        plan[METADATA_TABLE],
        ["db_source", "document_name"],
        METADATA_TABLE,
    )
    _require_columns(plan[CHUNKS_TABLE], ["db_source", "chunk_number"], CHUNKS_TABLE)
    return plan


def _require_columns(
    columns: Sequence[ColumnInfo],
    required_names: Sequence[str],
    table_name: str,
) -> None:
    """Raise if an expected import key is missing from the export plan."""
    names = {column.name for column in columns}
    missing = [name for name in required_names if name not in names]
    if missing:
        raise RuntimeError(f"{table_name} is missing required columns: {missing}")


def _print_dry_run(
    conn,
    table_columns: dict[str, list[ColumnInfo]],
    export_plan: dict[str, list[ColumnInfo]],
) -> None:
    """Print counts and generated-field handling without writing files."""
    registry_count = _fetch_count(conn, REGISTRY_TABLE)
    metadata_count = _fetch_count(conn, METADATA_TABLE)
    chunk_count = _fetch_count(conn, CHUNKS_TABLE)
    prompt_count = _fetch_latest_iris_prompt_count(conn)

    print("\nDry run")
    print(f"  {REGISTRY_TABLE}: {registry_count} rows")
    print(f"  latest iris prompts: {prompt_count} rows")
    print(f"  {METADATA_TABLE}: {metadata_count} rows")
    print(f"  {CHUNKS_TABLE}: {chunk_count} rows")
    print("\nGenerated columns omitted from exports")
    for table_name, excluded in GENERATED_COLUMNS.items():
        actual_columns = set(_column_names(table_columns[table_name]))
        omitted = sorted(excluded & actual_columns)
        print(f"  {table_name}: {', '.join(omitted)}")


def _fetch_count(conn, table_name: str) -> int:
    """Fetch a row count for a required table."""
    query = sql.SQL("SELECT COUNT(*) FROM {table}").format(
        table=sql.Identifier(table_name)
    )
    with conn.cursor() as cur:
        cur.execute(query)
        return int(cur.fetchone()[0])


def _fetch_latest_iris_prompt_count(conn) -> int:
    """Count latest-version prompt rows for model iris."""
    query = """
        SELECT COUNT(*)
        FROM (
            SELECT DISTINCT ON (layer, name) layer, name
            FROM prompts
            WHERE model = 'iris'
            ORDER BY layer, name, version DESC, updated_at DESC NULLS LAST
        ) latest_prompts
    """
    with conn.cursor() as cur:
        cur.execute(query)
        return int(cur.fetchone()[0])


def _iter_registry_rows(
    conn,
    columns: Sequence[ColumnInfo],
) -> Iterator[dict[str, Any]]:
    """Yield registry rows in stable db_source order."""
    query = _table_select_query(REGISTRY_TABLE, "r", columns, ["db_source"])
    yield from _iter_query(conn, query, _column_names(columns), "registry_export")


def _iter_latest_iris_prompt_rows(
    conn,
    columns: Sequence[ColumnInfo],
) -> Iterator[dict[str, Any]]:
    """Yield latest-version IRIS prompt rows using the application ordering rule."""
    query = sql.SQL(
        """
        SELECT DISTINCT ON (p.layer, p.name)
            {columns}
        FROM {table} p
        WHERE p.model = 'iris'
        ORDER BY
            p.layer,
            p.name,
            p.version DESC,
            p.updated_at DESC NULLS LAST,
            p.created_at DESC NULLS LAST
        """
    ).format(
        columns=_select_list("p", columns),
        table=sql.Identifier(PROMPTS_TABLE),
    )
    yield from _iter_query(conn, query, _column_names(columns), "prompts_export")


def _iter_metadata_rows(
    conn,
    columns: Sequence[ColumnInfo],
) -> Iterator[dict[str, Any]]:
    """Yield document metadata rows in stable document key order."""
    query = _table_select_query(
        METADATA_TABLE,
        "m",
        columns,
        ["db_source", "document_name"],
    )
    yield from _iter_query(conn, query, _column_names(columns), "metadata_export")


def _iter_chunk_rows(
    conn,
    columns: Sequence[ColumnInfo],
) -> Iterator[dict[str, Any]]:
    """Yield chunk rows with document natural keys for regenerated UUID mapping."""
    query = sql.SQL(
        """
        SELECT
            m.db_source AS document_db_source,
            m.document_name AS document_name,
            {chunk_columns}
        FROM {chunks_table} c
        JOIN {metadata_table} m ON m.id = c.document_id
        ORDER BY
            c.db_source,
            m.document_name,
            c.chunk_number,
            c.page_number,
            c.id
        """
    ).format(
        chunk_columns=_select_list("c", columns),
        chunks_table=sql.Identifier(CHUNKS_TABLE),
        metadata_table=sql.Identifier(METADATA_TABLE),
    )
    result_columns = _chunk_csv_columns(columns)
    yield from _iter_query(conn, query, result_columns, "chunks_export")


def _iter_direct_chunk_rows(
    conn,
    columns: Sequence[ColumnInfo],
) -> Iterator[dict[str, Any]]:
    """Yield direct chunk rows preserving table UUID columns."""
    query = _table_select_query(
        CHUNKS_TABLE,
        "c",
        columns,
        ["document_id", "chunk_number", "page_number", "id"],
    )
    yield from _iter_query(conn, query, _column_names(columns), "direct_chunks_export")


def _table_select_query(
    table_name: str,
    alias: str,
    columns: Sequence[ColumnInfo],
    order_columns: Sequence[str],
) -> sql.Composed:
    """Build a typed SELECT query for table export."""
    order_by = sql.SQL(", ").join(
        sql.SQL("{}.{}").format(sql.Identifier(alias), sql.Identifier(column_name))
        for column_name in order_columns
    )
    return sql.SQL("SELECT {columns} FROM {table} {alias} ORDER BY {order_by}").format(
        columns=_select_list(alias, columns),
        table=sql.Identifier(table_name),
        alias=sql.Identifier(alias),
        order_by=order_by,
    )


def _select_list(alias: str, columns: Sequence[ColumnInfo]) -> sql.Composed:
    """Build a SELECT list, casting vector columns to text for psycopg2."""
    expressions = []
    for column in columns:
        identifier = sql.SQL("{}.{}").format(
            sql.Identifier(alias),
            sql.Identifier(column.name),
        )
        if _is_vector_column(column):
            expressions.append(
                sql.SQL("{}::text AS {}").format(
                    identifier, sql.Identifier(column.name)
                )
            )
        else:
            expressions.append(identifier)
    return sql.SQL(", ").join(expressions)


def _iter_query(
    conn,
    query: sql.Composed,
    result_columns: Sequence[str],
    cursor_name: str,
) -> Iterator[dict[str, Any]]:
    """Stream query rows as dictionaries."""
    with conn.cursor(name=cursor_name) as cur:
        cur.itersize = 1000
        cur.execute(query)
        for record in cur:
            yield {column: value for column, value in zip(result_columns, record)}


def _write_csv(
    path: Path,
    columns: Sequence[str],
    rows: Iterable[dict[str, Any]],
    column_info: dict[str, ColumnInfo],
    null_value: str = NULL_SENTINEL,
) -> int:
    """Write rows to a CSV file using the configured NULL representation."""
    count = 0
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(columns)
        for row in rows:
            writer.writerow(
                [
                    _format_csv_value(
                        row.get(column),
                        column_info.get(column),
                        null_value=null_value,
                    )
                    for column in columns
                ]
            )
            count += 1
    print(f"  {path.name}: {count} rows")
    return count


def _write_direct_table_csvs(
    output_dir: Path,
    conn,
    table_columns: dict[str, list[ColumnInfo]],
) -> dict[str, int]:
    """Write exact table-shaped CSVs for direct table-by-table uploads."""
    direct_dir = output_dir / DIRECT_TABLE_CSV_DIR
    direct_dir.mkdir(parents=True, exist_ok=True)

    print(f"\nWriting direct table CSV exports to: {direct_dir}")
    registry_count = _write_csv(
        direct_dir / REGISTRY_FILE,
        _column_names(table_columns[REGISTRY_TABLE]),
        _iter_registry_rows(conn, table_columns[REGISTRY_TABLE]),
        _column_map(table_columns[REGISTRY_TABLE]),
    )
    prompt_count = _write_csv(
        direct_dir / PROMPTS_FILE,
        _column_names(table_columns[PROMPTS_TABLE]),
        _iter_latest_iris_prompt_rows(conn, table_columns[PROMPTS_TABLE]),
        _column_map(table_columns[PROMPTS_TABLE]),
    )
    metadata_count = _write_csv(
        direct_dir / METADATA_FILE,
        _column_names(table_columns[METADATA_TABLE]),
        _iter_metadata_rows(conn, table_columns[METADATA_TABLE]),
        _column_map(table_columns[METADATA_TABLE]),
    )
    chunk_count = _write_csv(
        direct_dir / CHUNKS_FILE,
        _column_names(table_columns[CHUNKS_TABLE]),
        _iter_direct_chunk_rows(conn, table_columns[CHUNKS_TABLE]),
        _column_map(table_columns[CHUNKS_TABLE]),
    )
    _write_direct_upload_sql(direct_dir / DIRECT_UPLOAD_SQL_FILE)
    return {
        REGISTRY_TABLE: registry_count,
        PROMPTS_TABLE: prompt_count,
        METADATA_TABLE: metadata_count,
        CHUNKS_TABLE: chunk_count,
    }


def _write_it_upload_csvs(
    output_dir: Path,
    conn,
    table_columns: dict[str, list[ColumnInfo]],
    prompt_rows: Sequence[dict[str, Any]],
    prompt_columns: Sequence[ColumnInfo],
) -> dict[str, int]:
    """Write the CSV bundle expected by IT's truncate/load process."""
    it_dir = output_dir / IT_UPLOAD_CSV_DIR
    it_dir.mkdir(parents=True, exist_ok=True)

    print(f"\nWriting IT upload CSV exports to: {it_dir}")
    registry_count = _write_csv(
        it_dir / REGISTRY_FILE,
        _column_names(table_columns[REGISTRY_TABLE]),
        _iter_registry_rows(conn, table_columns[REGISTRY_TABLE]),
        _column_map(table_columns[REGISTRY_TABLE]),
        null_value="",
    )
    prompt_count = _write_csv(
        it_dir / PROMPTS_FILE,
        _column_names(prompt_columns),
        prompt_rows,
        _column_map(prompt_columns),
        null_value="",
    )
    metadata_count = _write_csv(
        it_dir / METADATA_FILE,
        _column_names(table_columns[METADATA_TABLE]),
        _iter_metadata_rows(conn, table_columns[METADATA_TABLE]),
        _column_map(table_columns[METADATA_TABLE]),
        null_value="",
    )
    chunk_count = _write_csv(
        it_dir / CHUNKS_FILE,
        _column_names(table_columns[CHUNKS_TABLE]),
        _iter_direct_chunk_rows(conn, table_columns[CHUNKS_TABLE]),
        _column_map(table_columns[CHUNKS_TABLE]),
        null_value="",
    )
    _write_it_upload_readme(
        it_dir / README_FILE,
        {
            REGISTRY_TABLE: registry_count,
            PROMPTS_TABLE: prompt_count,
            METADATA_TABLE: metadata_count,
            CHUNKS_TABLE: chunk_count,
        },
    )
    return {
        REGISTRY_TABLE: registry_count,
        PROMPTS_TABLE: prompt_count,
        METADATA_TABLE: metadata_count,
        CHUNKS_TABLE: chunk_count,
    }


def _write_inline_sql(
    path: Path,
    registry_rows: Sequence[dict[str, Any]],
    prompt_rows: Sequence[dict[str, Any]],
    metadata_rows: Sequence[dict[str, Any]],
    conn,
    export_plan: dict[str, list[ColumnInfo]],
) -> int:
    """Write a self-contained SQL import file with regenerated generated fields."""
    registry_columns = _column_names(export_plan[REGISTRY_TABLE])
    prompt_columns = _column_names(export_plan[PROMPTS_TABLE])
    metadata_columns = _column_names(export_plan[METADATA_TABLE])
    chunk_columns = _column_names(export_plan[CHUNKS_TABLE])

    registry_info = _column_map(export_plan[REGISTRY_TABLE])
    prompt_info = _column_map(export_plan[PROMPTS_TABLE])
    metadata_info = _column_map(export_plan[METADATA_TABLE])
    chunk_info = _column_map(export_plan[CHUNKS_TABLE])

    chunk_count = 0
    with path.open("w", encoding="utf-8") as handle:
        _write_sql_header(handle, "Portable IRIS direct SQL import")
        handle.write("BEGIN;\n\n")

        handle.write("-- Registry rows are upserted by natural key: db_source.\n")
        for row in registry_rows:
            _write_upsert_values(
                handle,
                REGISTRY_TABLE,
                registry_columns,
                row,
                registry_info,
                ["db_source"],
                touch_updated_at=True,
            )

        handle.write("-- Latest IRIS prompts replace target model='iris' prompts.\n")
        handle.write(
            f"DELETE FROM {_ident(PROMPTS_TABLE)} WHERE {_ident('model')} = 'iris';\n\n"
        )
        for row in prompt_rows:
            _write_insert_values(
                handle, PROMPTS_TABLE, prompt_columns, row, prompt_info
            )

        _write_document_replacement_preamble(handle, metadata_rows)

        handle.write(
            "-- Document metadata rows regenerate id, created_at, and updated_at.\n"
        )
        for row in metadata_rows:
            _write_insert_values(
                handle,
                METADATA_TABLE,
                metadata_columns,
                row,
                metadata_info,
            )

        _write_document_presence_check(handle)

        handle.write(
            "-- Chunk rows regenerate id and created_at, and document_id is relinked.\n"
        )
        for row in _iter_chunk_rows(conn, export_plan[CHUNKS_TABLE]):
            _write_chunk_insert_select(handle, chunk_columns, row, chunk_info)
            chunk_count += 1

        handle.write("COMMIT;\n")
